CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 full_name VARCHAR(160) NOT NULL,
 login_name VARCHAR(190) NOT NULL,
 role ENUM('student','teacher','admin') NOT NULL,
 grade VARCHAR(20) NULL, field_name VARCHAR(40) NULL, branch VARCHAR(20) NULL,
 password_hash VARCHAR(255) NOT NULL, must_change_password TINYINT(1) NOT NULL DEFAULT 1,
 active TINYINT(1) NOT NULL DEFAULT 1, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uniq_login_name(login_name), KEY idx_role(role)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS teacher_scopes (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL,
 grade VARCHAR(20) NOT NULL, field_name VARCHAR(40) NOT NULL, branch VARCHAR(20) NOT NULL, subject_name VARCHAR(80) NOT NULL,
 CONSTRAINT fk_scope_user FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 UNIQUE KEY uniq_teacher_scope(user_id,grade,field_name,branch,subject_name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS lessons (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, `group` VARCHAR(120) NOT NULL, day VARCHAR(24) NOT NULL,
 dayOrder TINYINT NOT NULL DEFAULT 0, `time` VARCHAR(40) NOT NULL, timeOrder SMALLINT NOT NULL DEFAULT 0,
 name VARCHAR(100) NOT NULL, teacher VARCHAR(160) NULL, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 KEY idx_lesson_group_day(`group`,dayOrder,timeOrder)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS tasks (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, `group` VARCHAR(120) NOT NULL, day VARCHAR(24) NOT NULL,
 dayOrder TINYINT NOT NULL DEFAULT 0, title VARCHAR(180) NOT NULL, `desc` TEXT NULL,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 KEY idx_task_group_day(`group`,dayOrder)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
